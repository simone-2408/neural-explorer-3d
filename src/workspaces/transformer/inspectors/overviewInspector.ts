/** Transformer inspector with nothing selected: what the model is, what you see, the pipeline. */
import { parameterCount } from '../../../transformer/model';
import { topTokens } from '../../../transformer/analysis';
import { h } from '../../../ui/dom';
import type { InspectorView } from '../../../ui/InspectorPanel';
import { tex } from '../../../ui/tex';
import { kv, note } from '../../../ui/widgets';
import { formatCount, formatPercent, formatValue } from '../../../utils/format';
import { block, entityLink, inspectorHeader, paragraph } from '../../network/inspectors/common';
import type { TransformerWorkspace } from '../TransformerWorkspace';
import { quote } from './common';

export function overviewInspector(ws: TransformerWorkspace): InspectorView {
  const model = ws.model!;
  const trace = ws.trace!;
  const { config, training } = model;
  const T = trace.tokens.length;
  const last = T - 1;
  const best = topTokens(model, trace.logits[last], 1)[0];

  const pipeline = h(
    'ol',
    { class: 'pipeline-list' },
    h('li', null, entityLink('Tokens', () => ws.select({ kind: 'token', position: last, stage: 0 }), 'Inspect the last token'), ' — the text becomes word indices.'),
    h('li', null, entityLink('Embedding', () => ws.select({ kind: 'token', position: last, stage: 0 })), ` — each index selects a vector of ${config.dModel} numbers; its position adds another.`),
    Array.from({ length: config.nLayers }, (_, l) => [
      h('li', null, entityLink(`Attention ${l + 1}`, () => ws.select({ kind: 'attention', layer: l })), ` — ${config.nHeads} heads let each token read earlier tokens.`),
      h('li', null, entityLink(`MLP ${l + 1}`, () => ws.select({ kind: 'mlp', layer: l, position: last })), ` — ${config.dModel} → ${config.dMlp} → ${config.dModel}, each position on its own.`),
    ]),
    h('li', null, entityLink('Prediction', () => ws.select({ kind: 'prediction', position: last })), ' — scores for every word, turned into probabilities.'),
  );

  const el = h(
    'div',
    { class: 'inspector-view' },
    inspectorHeader({
      kind: 'Toy Transformer',
      title: `${config.nLayers} layers · ${config.nHeads} heads · d = ${config.dModel}`,
      subtitle: `${formatCount(parameterCount(model))} parameters · ${config.vocab.length}-word vocabulary · GPT-style`,
    }),
    block(
      1,
      'What you see',
      paragraph('Columns are the tokens of your text. Rows are the residual stream at successive stages: the embeddings at the bottom, then the vectors after each attention and each MLP. Every slab is one vector of 32 numbers, drawn as bars along the depth.'),
      paragraph('Between two rows sits a sub-layer that adds its output to every vector: attention, whose arcs show which earlier tokens each token reads (the only place where tokens exchange information), or the MLP, one block per token.'),
      paragraph(`At the top: the probabilities of the next word. Now: ${quote(best.text)} with ${formatPercent(best.value, 1)}. Click anything to inspect it; press ▶ at the bottom to watch the computation step by step.`),
    ),
    block(null, 'The computation', pipeline),
    block(
      2,
      null,
      kv('Vocabulary · context', `${config.vocab.length} words · ${config.context} tokens`),
      kv('Vector size d_model', String(config.dModel)),
      kv('Heads × size', `${config.nHeads} × ${config.dModel / config.nHeads}`),
      kv('MLP hidden units', String(config.dMlp)),
      kv('Parameters', formatCount(parameterCount(model))),
      kv('Training', `${formatCount(training.sentences)} sentences · ${formatCount(training.steps)} steps (AdamW)`),
      kv('Final training loss', formatValue(training.finalLoss, 3)),
    ),
    block(
      null,
      'What it learned',
      paragraph('Everything this model knows comes from sentences generated by these templates:'),
      h(
        'ul',
        { class: 'template-list' },
        training.templates.map((t) => h('li', null, h('code', null, t))),
      ),
      paragraph('Some answers it gives (top word and probability, computed when it was trained):'),
      h(
        'ul',
        { class: 'probe-list' },
        training.probes.map((p) =>
          h(
            'li',
            null,
            h('button', { type: 'button', class: 'entity-link', onClick: () => ws.loadExample(p.text) }, p.text),
            ` → ${p.top[0][0]} (${formatPercent(p.top[0][1], 1)})`,
          ),
        ),
      ),
    ),
    block(
      3,
      null,
      tex('x^{(0)}_p = E_{t_p} + P_p', { display: true }),
      tex('x \\leftarrow x + \\operatorname{Attn}\\big(\\operatorname{LN}_1(x)\\big), \\qquad x \\leftarrow x + \\operatorname{MLP}\\big(\\operatorname{LN}_2(x)\\big)', { display: true }),
      tex('P(t_{p+1} \\mid t_{\\le p}) = \\operatorname{softmax}\\big(\\operatorname{LN}_f(x_p)\\, E^{\\top}\\big)', { display: true }),
      paragraph('E is used twice: to turn words into vectors and, transposed, to score every word at the end (tied embeddings, as in GPT-2).'),
    ),
    block(
      null,
      'Keep in mind',
      note(`A toy: ${formatCount(parameterCount(model))} parameters trained in under a minute on synthetic sentences. It continues the patterns of its training data; it does not understand them. GPT-2 small (LLM tab) has the same architecture with 124 million parameters, 12 layers and 12 heads per layer.`),
      note('This browser implementation is checked against PyTorch: the logits match to 8 decimals (src/transformer/transformer.test.ts).'),
    ),
  );
  return { el, update: () => {} };
}
